# Lists Methods

list = [2,1,6,3,5]
print(list)

# append
list.append(4)
print(list)

# Sorting (in Ascending order)
list.sort()
print(list)

# Sorting (in descending order)
list.sort(reverse = True)
print(list)

# Reverse
list.reverse()
print(list)

# Inserting
list.insert(1, 9)
print(list)

# Remove
list.remove(9)
print(list)

# removeing from specific index
list.pop(1)
print(list)

